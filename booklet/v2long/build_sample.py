#!/usr/bin/env python3
"""Build sample.tex (the W13 sample questions, solved) by copying the solution boxes
out of the week files, so the appendix and the weeks can never disagree.
Run after editing any week file:  python3 build_sample.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))

# (question, week file, title prefix to find, figure line to put before the box or None)
PICKS = [
    ('Q1', 'w02', r'W13 Q1:', None),
    ('Q2', 'w03', r'W13 Q2', None),
    ('Q3', 'w03', r'W13 Q3', None),
    ('Q4', 'w07', r'W13 Q4 (a)', None),
    ('Q5', 'w04', r'W13 Q5', r'\slidefig[0.85\linewidth]{w13-lec}{9}{0 76 48 92}{W13 p.\,9: the question (K and $\phi$ given; find $\theta_1,\varphi_1,\varphi_2,\varphi_3$)}'),
    ('Q6', 'w01', r'W13 Q6', None),
    ('Q7', 'w04', r'W13 Q7', r'\slidefig[0.85\linewidth]{w13-lec}{14}{0 76 67 108}{W13 p.\,14: the delta mechanism and its joint graph (B base, R, S, S, M moving platform)}'),
    ('Q8', 'w05', r'W13 Q8', None),
    ('Q9', 'w05', r'W13 Q9', None),
    ('Q10', 'w10', r'(W13 Q10)', None),
]

BEGIN = r'\begin{examq}'
END = r'\end{examq}'


def boxes(text):
    """Yield (start, end, title) of every examq box."""
    i = 0
    while True:
        s = text.find(BEGIN, i)
        if s < 0:
            return
        e = text.find(END, s)
        title = text[s + len(BEGIN):text.find('\n', s)]
        yield s, e + len(END), title
        i = e


def pick(week, prefix):
    text = open(os.path.join(HERE, week + '.tex')).read()
    bs = list(boxes(text))
    for k, (s, e, title) in enumerate(bs):
        if title.lstrip('[').startswith(prefix):
            out = [text[s:e]]
            # continuation boxes directly after (title says cont.)
            for s2, e2, t2 in bs[k + 1:]:
                gap = text[e:s2]
                if 'cont' in t2 and gap.strip() == '':
                    out.append(text[s2:e2]); e = e2
                else:
                    break
            return out
    raise SystemExit(f'{week}: no examq starting with {prefix!r}')


def main():
    parts = [r'% GENERATED by build_sample.py from the week files. Do not edit by hand.',
             r'\bpart{SAMPLE}{W13 sample questions, solved (copied from the weeks)}{17}',
             r'{\small The ten questions of the W13 revision lecture, in order, each with the model answer from its week. '
             r'Marks are not published; indicative only. The week page has the method, traps and variations.\par}',
             r'\begin{multicols}{2}']
    for q, week, prefix, fig in PICKS:
        wk = int(week[1:])
        parts.append(rf'\hd{{Sample {q} \textmd{{\small(W{wk}, p.\,\pageref{{p:W{wk}}})}}}}')
        if fig:
            parts.append(fig)
        parts.extend(re.sub(r'\\label\{[^}]*\}', '', b) for b in pick(week, prefix))
    parts.append(r'\end{multicols}')
    open(os.path.join(HERE, 'sample.tex'), 'w').write('\n'.join(parts) + '\n')
    print('sample.tex written')


if __name__ == '__main__':
    main()
